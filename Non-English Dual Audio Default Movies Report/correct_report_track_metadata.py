def find_executable(command_name: str) -> str | None:
    """
    Find an executable on PATH or common MKVToolNix Windows paths.

    :param command_name: Executable name.
    :return: Executable path or None.
    """

    path_result = shutil.which(command_name)  # Search PATH first.
    if path_result is not None:  # Validate PATH lookup result.
        return path_result  # Return PATH executable.

    if os.name == "nt" and command_name.lower() in {"mkvpropedit", "mkvmerge", "ffprobe", "ffmpeg"}:  # Use known Windows install roots for media tools.
        executable_name = f"{command_name}.exe"  # Build Windows executable name.
        program_dirs = [os.environ.get("ProgramFiles"), os.environ.get("ProgramFiles(x86)")]  # Read standard program directories.
        for program_dir in program_dirs:  # Iterate program directories.
            if not program_dir:  # Skip missing environment values.
                continue  # Continue with next install root.
            mkv_candidate = Path(program_dir) / "MKVToolNix" / executable_name  # Build MKVToolNix candidate path.
            if mkv_candidate.exists():  # Validate MKVToolNix candidate.
                return str(mkv_candidate)  # Return discovered executable.

    return None  # Return missing executable.


def acquire_file_lock(lock_path: Path, owner_text: str) -> FileLock:
    """
    Acquire one exclusive file lock and return its handle.

    :param lock_path: Lock file path.
    :param owner_text: Diagnostic owner text.
    :return: Acquired file lock handle.
    """

    lock_path.parent.mkdir(parents=True, exist_ok=True)  # Ensure lock directory exists.
    stream = lock_path.open("a+", encoding="utf-8")  # Open coordination file.
    try:  # Acquire operating-system lock before writing owner data.
        if os.name == "nt":  # Use Windows byte-range locking on Windows.
            import msvcrt  # Import Windows lock support only on Windows.
            while True:  # Retry until lock becomes available.
                try:  # Attempt non-blocking Windows lock acquisition.
                    stream.seek(0)  # Move to selected byte.
                    msvcrt.locking(stream.fileno(), msvcrt.LK_NBLCK, LOCK_BYTE_COUNT)  # Acquire one-byte exclusive lock.
                    break  # Stop retrying after lock acquisition.
                except OSError:  # Handle lock owned by another process.
                    time.sleep(LOCK_RETRY_SECONDS)  # Wait before retrying.
        else:  # Use POSIX flock elsewhere.
            import fcntl  # Import POSIX lock support only on POSIX.
            fcntl.flock(stream.fileno(), fcntl.LOCK_EX)  # Acquire exclusive POSIX lock.

        stream.seek(0)  # Move to beginning before diagnostics write.
        stream.truncate(0)  # Remove previous diagnostics while owning lock.
        stream.write(f"{owner_text.rstrip()}\n")  # Write current owner diagnostics.
        stream.flush()  # Flush owner diagnostics.
        return FileLock(lock_path, stream)  # Return handle-owned lock.
    except Exception:  # Close stream after failed lock acquisition.
        stream.close()  # Close stream to release partial state.
        raise  # Propagate lock failure.


def release_file_lock(file_lock: FileLock) -> None:
    """
    Release one acquired file lock.

    :param file_lock: Acquired file lock.
    :return: None.
    """

    try:  # Release operating-system lock.
        if os.name == "nt":  # Use Windows byte-range unlocking on Windows.
            import msvcrt  # Import Windows lock support only on Windows.
            file_lock.stream.seek(0)  # Move to selected byte.
            msvcrt.locking(file_lock.stream.fileno(), msvcrt.LK_UNLCK, LOCK_BYTE_COUNT)  # Release one-byte lock.
        else:  # Use POSIX flock elsewhere.
            import fcntl  # Import POSIX lock support only on POSIX.
            fcntl.flock(file_lock.stream.fileno(), fcntl.LOCK_UN)  # Release POSIX lock.
    except OSError:  # Ignore release attempts for invalid lock state.
        pass  # Preserve cleanup stability.
    finally:  # Close owning stream.
        file_lock.stream.close()  # Close lock file stream.


def build_media_lock_path(file_path: Path) -> Path:
    """
    Build a cross-process lock path for one media file.

    :param file_path: Media file path.
    :return: Lock file path.
    """

    resolved_path = file_path.resolve(strict=False)  # Resolve media path without requiring existence.
    lock_identity = str(resolved_path).casefold() if os.name == "nt" else str(resolved_path)  # Normalize Windows path casing.
    lock_hash = hashlib.sha256(lock_identity.encode("utf-8")).hexdigest()  # Build deterministic lock identity.
    return MEDIA_LOCK_DIRECTORY / f"{lock_hash}.lock"  # Return lock file path.


def acquire_media_edit_lock(file_path: Path) -> FileLock:
    """
    Acquire an exclusive edit lock for one media file.

    :param file_path: Media file path.
    :return: Acquired file lock handle.
    """

    lock_path = build_media_lock_path(file_path)  # Build target lock path.
    owner_text = f"pid={os.getpid()}\nfile={file_path.resolve(strict=False)}\n"  # Build diagnostic lock payload.
    return acquire_file_lock(lock_path, owner_text)  # Return media edit lock.


def run_json_command(command: list[str], failure_label: str) -> dict[str, Any]:
    """
    Run one JSON-producing command and return parsed output.

    :param command: Command argument vector.
    :param failure_label: Context label for errors.
    :return: Parsed JSON object.
    """

    try:  # Run external tool without shell expansion.
        result = subprocess.run(command, capture_output=True, text=True, encoding="utf-8", errors="replace")  # Execute command.
    except OSError as error:  # Handle executable launch failure.
        raise RuntimeError(f"{failure_label} could not start: {error}") from error  # Raise contextual launch error.

    if result.returncode != 0:  # Validate tool success.
        details = (result.stderr or result.stdout).strip() or "No diagnostic output was provided."  # Read tool diagnostics.
        raise RuntimeError(f"{failure_label} failed: {details}")  # Raise contextual tool failure.

    try:  # Parse tool JSON output.
        parsed_data = json.loads(result.stdout) if result.stdout else {}  # Decode JSON payload.
    except json.JSONDecodeError as error:  # Handle invalid JSON output.
        raise RuntimeError(f"{failure_label} returned invalid JSON.") from error  # Raise contextual JSON error.

    if not isinstance(parsed_data, dict):  # Validate expected JSON object shape.
        raise RuntimeError(f"{failure_label} returned unexpected JSON shape.")  # Raise contextual shape error.

    return parsed_data  # Return parsed object.


def probe_ffprobe(file_path: Path) -> dict[str, Any]:
    """
    Probe media through ffprobe.

    :param file_path: Media file path.
    :return: Parsed ffprobe metadata.
    """

    executable = find_executable("ffprobe")  # Locate ffprobe.
    if executable is None:  # Validate ffprobe availability.
        raise RuntimeError("ffprobe not found.")  # Raise missing-tool error.
    command = [executable, "-v", "error", "-show_streams", "-show_format", "-of", "json", str(file_path)]  # Build read-only ffprobe command.
    return run_json_command(command, f"ffprobe for {file_path}")  # Return parsed metadata.


