SRT_TEXT_ENCODINGS = ("utf-8-sig", "utf-8", "cp1252", "latin-1")  # Common subtitle encodings
STRICT_TIMESTAMP_PATTERN = re.compile(
    r"^\d{2}:\d{2}:\d{2},\d{3}\s+-->\s+\d{2}:\d{2}:\d{2},\d{3}(?:\s+.*)?$"
)  # Strict output SRT timestamp syntax
REPAIRABLE_TIMESTAMP_PATTERN = re.compile(
    r"^(?P<start_h>\d{1,2}):(?P<start_m>\d{1,2}):(?P<start_s>\d{1,2}),(?P<start_ms>\d+)"
    r"\s+-->\s+"
    r"(?P<end_h>\d{1,2}):(?P<end_m>\d{1,2}):(?P<end_s>\d{1,2}),(?P<end_ms>\d+)"
    r"(?P<suffix>(?:\s+.*)?)$"
)  # Timestamp syntax that can be normalized safely


