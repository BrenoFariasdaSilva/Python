"""
================================================================================
Subtitle Credits-Promotional Content Remover
================================================================================
Author      : Breno Farias da Silva
Created     : 2026-08-23
Description :
    Consumes grouped JSON reports generated by detect.py and removes only the exact
    SRT blocks referenced by those reports.

    The remover does not re-detect content. It verifies each source file SHA-256,
    verifies every target block against its stored SHA-256/index/timestamp/text,
    removes the exact reported blocks, renumbers all remaining SRT blocks
    sequentially, validates the resulting structure, and publishes changes
    atomically in place.

    Key features include:
        - Report-driven removal only; no independent heuristic decisions
        - SHA-256 source-file verification before any modification
        - Exact block identity verification before removal
        - Safe deduplication of grouped report occurrences
        - Sequential SRT renumbering after removals
        - Strict output validation before atomic replacement
        - Repair of safely normalizable timestamp-width/fraction formatting
        - Logger integration and one colored progress bar per input report

Usage:
    1. Run detect.py and review ./Outputs/*-report.json.
    2. Keep SRT files unchanged between detection and removal.
    3. Copy the repository's existing Logger.py beside this script.
    4. Execute:
        $ python remove.py

Outputs:
    - Modified original SRT files when exact report verification succeeds
    - ./Logs/remove.log

TODOs:
    - Add an optional backup mode if historical source preservation is desired.

Dependencies:
    - Python >= 3.10
    - colorama
    - tqdm
    - Local Logger.py from the repository template

Assumptions & Notes:
    - REQUIRE_FILE_HASH_MATCH=True prevents stale-report removal.
    - If a file changed after detection, that file is skipped rather than guessed.
    - Only blocks present in reviewed detector reports are eligible for removal.
    - Paths stored/read from reports use forward slashes.
"""

